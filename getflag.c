#include <stdlib.h>
char *get_flag(char *encflag,char *key,int size,int keysize)

{
  char *flag;
  int i;
  
  flag = (char *)malloc(size + 1);
  for (i = 0; i < size; i = i + 1) {
    flag[i] = key[i % keysize] ^ encflag[i];
  }
  flag[size] = '\0';
  return flag;
}

